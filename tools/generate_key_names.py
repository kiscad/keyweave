#!/usr/bin/env python3
"""Generate factual HID name/usage data from the audited source snapshot."""
import hashlib
import json
from pathlib import Path
import re

project = Path(__file__).resolve().parents[1]
source = project.parent / 'Karabiner-Elements'
usage_path = 'vendor/vendor/include/pqrs/hid/usage.hpp'
usage = (source / usage_path).read_text()
rows = []
inputs = [usage_path]
for category, page in [('key_code', 7), ('consumer_key_code', 12)]:
    path = f'src/share/types/momentary_switch_event_details/{category}.hpp'
    inputs.append(path)
    text = (source / path).read_text()
    namespace = 'keyboard_or_keypad' if page == 7 else 'consumer'
    section = usage.split(f'namespace {namespace} {{')[1].split(f'}} // namespace {namespace}')[0]
    constants = {name: int(value, 16) for name, value in re.findall(r'constexpr value_t (\w+)\((0x[0-9a-fA-F]+)\)', section)}
    constants['undefined'] = 0
    for name, symbol in re.findall(r'\{"([^"]+)", pqrs::hid::usage::(?:\w+::)?(\w+)\}', text):
        rows.append((page, name, constants[symbol]))
dest = project / 'crates/keyweave-types/src/key_names.rs'
body = ['// Generated by tools/generate_key_names.py; see NOTICE.md.',
        '// HID constants: Copyright Takayama Fumihiko 2020, Boost-1.0.',
        '// Karabiner key names: Unlicense, source commit ec2fea8940f7254a748c052a890ee9db7113d9b1.',
        'pub(crate) const NAMES: &[(u16, &str, u16)] = &[']
body.extend(f'    (0x{page:02x}, "{name}", 0x{value:04x}),' for page, name, value in rows)
body.append('];')
dest.write_text('\n'.join(body) + '\n')
manifest = {'source_commit': 'ec2fea8940f7254a748c052a890ee9db7113d9b1', 'entries': len(rows),
            'files': [{'path': path, 'sha256': hashlib.sha256((source/path).read_bytes()).hexdigest()} for path in inputs]}
(project / 'docs/key-names-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Generated {len(rows)} key names')
