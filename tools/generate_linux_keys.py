#!/usr/bin/env python3
"""Generate reviewed Linux/HID numeric facts; optional local UAPI cross-check."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
parser.add_argument('--header', type=Path)
args = parser.parse_args()
data = json.loads((ROOT / 'data/linux-key-facts.json').read_text())
assert data['schema_version'] == 1
rows = data['rows']
seen = set()
canonical = {}
for row in rows:
    key = row['page'], row['usage']
    assert row['page'] in (7, 12) and 0 < row['usage'] <= 65535
    assert 0 < row['code'] <= 0x2ff and isinstance(row['canonical'], bool)
    assert key not in seen
    seen.add(key)
    if row['canonical']:
        assert row['code'] not in canonical
        canonical[row['code']] = key
assert all(row['code'] in canonical for row in rows)
if args.header:
    definitions = dict(re.findall(r'^#define\s+(KEY_\w+)\s+(0x[0-9a-fA-F]+|\d+|KEY_\w+)\b', args.header.read_text(), re.M))
    def value(name):
        raw = definitions[name]
        return value(raw) if raw.startswith('KEY_') else int(raw, 0)
    assert all(value(row['native_name']) == row['code'] for row in rows)
lines = ['// Generated by tools/generate_linux_keys.py from reviewed numeric facts.',
         '// No Linux kernel implementation is copied; see ADR-0019.',
         'use super::Mapping;', 'use keyweave_types::KeyId;',
         'pub(super) const MAPPINGS: &[Mapping] = &[']
for row in rows:
    lines.append(f"    Mapping {{ key: KeyId::new(0x{row['page']:02x}, 0x{row['usage']:04x}), code: {row['code']}, canonical: {str(row['canonical']).lower()} }}, // {row['native_name']}")
lines += ['];', '']
# Match rustfmt so --check can run on either OS without a local UAPI header.
import subprocess
rendered = subprocess.run(['rustfmt', '--edition', '2024'], input='\n'.join(lines), text=True, capture_output=True, check=True).stdout
path = ROOT / 'crates/keyweave-linux/src/keys/table.rs'
if args.check:
    assert path.read_text() == rendered, 'generated table differs'
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered)
print(f'Verified {len(rows)} mappings, {len(canonical)} canonical native codes')
